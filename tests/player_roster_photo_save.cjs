const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let buttons=[{dataset:{savePlayerPhotos:'p'},hidden:true,disabled:false,textContent:''},{dataset:{savePlayerPhotos:'auto'},hidden:true,disabled:false,textContent:''}];
const ctx=vm.createContext({document:{querySelector(){return null},querySelectorAll(s){return s.includes('data-save-player-photos')?buttons:[]},addEventListener(){}},window:{},console,setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync('scripts/volleyball_ui/static/app.js','utf8'),ctx);
vm.runInContext('state.project="project";state.video="match";analysisCacheId=()=>"cache";state.report={groups:[{id:"p",track_ids:[1]}]};',ctx);
(async()=>{
  let requests=0;
  ctx.api=async()=>{requests++;return {counts:{p:2,auto:0}}};
  await vm.runInContext('refreshRosterPhotoButtons()',ctx);
  assert.equal(buttons[0].hidden,false);
  assert.match(buttons[0].textContent,/2/);
  assert.equal(buttons[1].hidden,true);
  buttons=buttons.map(b=>({...b,hidden:true}));
  await vm.runInContext('refreshRosterPhotoButtons()',ctx);
  assert.equal(requests,1);
  assert.equal(buttons[0].hidden,false);
  let finish;
  vm.runInContext('state.video="new"',ctx);
  ctx.api=()=>new Promise(resolve=>{finish=resolve});
  const pending=vm.runInContext('refreshRosterPhotoButtons()',ctx);
  vm.runInContext('state.video="other"',ctx);
  buttons[0].hidden=true;
  finish({counts:{p:10}});
  await pending;
  assert.equal(buttons[0].hidden,true);
  ctx.api=async()=>({counts:{p:0}});
  await vm.runInContext('refreshRosterPhotoButtons()',ctx);
  assert.equal(buttons[0].hidden,true);
  console.log('PASS: roster photo count, empty state, cache reuse and stale response protection');
})().catch(error=>{console.error(error);process.exitCode=1});
